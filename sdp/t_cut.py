"""Level-k relaxation for one T state, solved by facets + cutting planes.

Same relaxation as t_lp.py. The cone generated by the aggregated distributions of all stabilizer
states on k+1 qubits is converted once to its facet description {g : F g >= 0} (qhull). For a
conditioning state s with weight distribution m, the contracted Choi vector is the linear map
    g_s(j,b) = C(k,j) sum_v m_v lam[j+v, b],
so each pair (facet, conditioning state) gives one linear inequality in lam. We start with none,
solve, add the most violated pairs, and repeat until no pair is violated (feasible) or the LP
becomes infeasible (a proof that no protocol exists, for this relaxation and these states).
"""
import math
import sys
import time
import numpy as np
import gurobipy as gp
from gurobipy import GRB
from scipy.spatial import ConvexHull

from t_lp import generators, conditioning_set

_FACETS = {}


def facets(k):
    """Rows f with f.g >= 0 for every generator g (homogeneous description of the cone)."""
    if k in _FACETS:
        return _FACETS[k]
    G = generators(k)
    G = G / G.sum(axis=1, keepdims=True)
    c = G.mean(axis=0)
    # coordinates in the affine hull
    U, S, Vt = np.linalg.svd(G - c, full_matrices=False)
    r = int((S > 1e-9).sum())
    B = Vt[:r]                      # basis of the affine hull directions
    P = (G - c) @ B.T
    hull = ConvexHull(P)
    F = []
    for eq in hull.equations:       # a.p + b <= 0 inside
        a, b = eq[:-1], eq[-1]
        # a.(B (g - c)) + b <= 0 for g with sum 1  ->  f.g >= 0 with f = -(B^T a) - (b - a.B c) * 1
        f = -(B.T @ a) - (b - a @ (B @ c)) * np.ones(G.shape[1])
        F.append(f)
    F = np.unique(np.round(np.array(F), 12), axis=0)
    assert (G @ F.T >= -1e-9).all()
    _FACETS[k] = F
    return F


def contraction_matrix(n, k, mvec):
    """Matrix A with g_s = A @ vec(lam), vec index v*2+b, g index j*2+b."""
    R = len(mvec) - 1
    A = np.zeros(((k + 1) * 2, (n + 1) * 2))
    for j in range(k + 1):
        for b in range(2):
            for v in range(R + 1):
                A[j * 2 + b, (j + v) * 2 + b] += math.comb(k, j) * mvec[v]
    return A


def solve(n, d, levels, rng=None, n_random=2000, max_rounds=2000, verbose=False, galois=False):
    rng = rng or np.random.default_rng(0)
    blocks = []                      # list of (F, list of A matrices)
    for k in levels:
        if k > n:
            continue
        R = n - k
        ms = conditioning_set(R, rng, n_random) if R > 0 else np.array([[1.0]])
        F = facets(k)
        As = np.array([contraction_matrix(n, k, mv) for mv in ms])   # (#m, rows, cols)
        blocks.append((F, As))
    m = gp.Model()
    m.Params.OutputFlag = 0
    x = m.addMVar((n + 1) * 2, lb=0.0)
    for v in range(min(d, n + 1)):
        m.addConstr(x[v * 2 + 1] == 0)
    m.addConstr(x[0] == 1)
    if galois:
        # sqrt2 -> -sqrt2 swaps |T> and Z|T>: complements of harmless patterns output exactly Z|T>
        for w in range(max(0, n - d + 1), n + 1):
            m.addConstr(x[w * 2] == 0)
    m.setObjective(x.sum(), GRB.MINIMIZE)     # keeps the LP bounded
    added = 0
    for rnd in range(max_rounds):
        m.optimize()
        if m.Status != GRB.OPTIMAL:
            return False, None, added
        lam = x.X
        new = 0
        for F, As in blocks:
            V = np.einsum("fr,mrc,c->mf", F, As, lam)   # (#m, #facets) values f.(A lam)
            bad = np.argwhere(V < -1e-9)
            if len(bad) == 0:
                continue
            # most violated facet per conditioning state, capped
            order = np.argsort(V[bad[:, 0], bad[:, 1]])[:500]
            for i in order:
                mi, fi = bad[i]
                row = F[fi] @ As[mi]
                m.addConstr(row @ x >= 0)
                new += 1
        added += new
        if verbose:
            print(f"  round {rnd}: added {new}", flush=True)
        if new == 0:
            return True, lam.reshape(n + 1, 2), added
    raise RuntimeError("cutting planes did not converge")


if __name__ == "__main__":
    levels = tuple(int(x) for x in sys.argv[1].split(","))
    ds = [int(x) for x in sys.argv[2].split(",")]
    galois = len(sys.argv) > 3 and sys.argv[3] == "galois"
    nmax = 40
    for d in ds:
        t0 = time.time()
        n = d
        while n <= nmax:
            feas, lam, added = solve(n, d, levels, galois=galois)
            if feas:
                break
            n += 1
        print(f"T d={d} levels={levels} galois={galois}: first n not excluded = {n}  [{time.time()-t0:.0f}s]", flush=True)
